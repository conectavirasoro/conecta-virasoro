-- Conecta Virasoro: esquema inicial de publicaciones para Supabase
-- Ejecutar en Supabase > SQL Editor > New query.
-- Seguridad: las visitas públicas solo ven publicaciones aprobadas y solo pueden enviar pendientes.
-- La administración requiere un usuario autenticado cuyo app_metadata.role sea "admin".

create table if not exists public.publicaciones (
  id bigint generated by default as identity primary key,
  categoria text not null,
  tipo_aviso text,
  titulo text not null,
  descripcion text not null,
  zona text,
  precio text,
  contacto text not null,
  redes_url text,
  imagen_url text,
  instagram_url text,
  facebook_url text,
  tiktok_url text,
  website_url text,
  estado text not null default 'pendiente'
    check (estado in ('pendiente', 'aprobada', 'rechazada')),
  created_at timestamptz not null default now()
);

create index if not exists publicaciones_estado_created_at_idx
  on public.publicaciones (estado, created_at desc);

create index if not exists publicaciones_categoria_idx
  on public.publicaciones (categoria);

alter table public.publicaciones enable row level security;

-- Retira políticas iniciales con estos nombres si se vuelve a ejecutar el script.
drop policy if exists "Public can read approved publications" on public.publicaciones;
drop policy if exists "Public can submit pending publications" on public.publicaciones;
drop policy if exists "Admins can manage all publications" on public.publicaciones;

create policy "Public can read approved publications"
on public.publicaciones for select
to anon, authenticated
using (
  estado = 'aprobada'
  or (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
);

create policy "Public can submit pending publications"
on public.publicaciones for insert
to anon, authenticated
with check (estado = 'pendiente');

create policy "Admins can manage all publications"
on public.publicaciones for all
to authenticated
using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

-- Impide que una solicitud pública intente publicarse directamente como aprobada.
create or replace function public.force_publication_pending()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if coalesce(auth.jwt() -> 'app_metadata' ->> 'role', '') <> 'admin' then
    new.estado := 'pendiente';
  end if;
  return new;
end;
$$;

drop trigger if exists force_publication_pending on public.publicaciones;
create trigger force_publication_pending
before insert on public.publicaciones
for each row execute function public.force_publication_pending();

grant select, insert on public.publicaciones to anon, authenticated;
grant update, delete on public.publicaciones to authenticated;
grant usage, select on sequence public.publicaciones_id_seq to anon, authenticated;
